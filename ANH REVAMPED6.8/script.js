/* =========================================================

   SCROLL REVEAL — IntersectionObserver

========================================================= */

function initScrollReveal() {

  const revealElements = document.querySelectorAll("[data-reveal], [data-reveal-stagger]");

  if (!revealElements.length) return;



  document.documentElement.classList.add("reveal-ready");



  const reveal = (el) => el.classList.add("visible");

  const inViewport = (el) => {

    const r = el.getBoundingClientRect();

    return r.top < (window.innerHeight - 12) && r.bottom > 0;

  };



  if (!("IntersectionObserver" in window)) {

    revealElements.forEach(reveal);

    return;

  }



  revealElements.forEach((el) => { if (inViewport(el)) reveal(el); });



  let observer;

  try {

    observer = new IntersectionObserver(

      (entries) => {

        entries.forEach((entry) => {

          if (entry.isIntersecting) {

            reveal(entry.target);

            observer.unobserve(entry.target);

          }

        });

      },

      { threshold: 0, rootMargin: "0px 0px -10px 0px" }

    );

  } catch (err) {

    revealElements.forEach(reveal);

    return;

  }



  revealElements.forEach((el) => {

    if (!el.classList.contains("visible")) observer.observe(el);

  });



  let sweepDone = false;

  let sweepQueued = false;

  const sweep = () => {

    if (sweepQueued) return;

    sweepQueued = true;

    requestAnimationFrame(() => {

      sweepQueued = false;

      if (sweepDone) return;

      let allVisible = true;

      revealElements.forEach((el) => {

        if (!el.classList.contains("visible")) {

          if (inViewport(el)) reveal(el);

          else allVisible = false;

        }

      });

      if (allVisible) {

        sweepDone = true;

        window.removeEventListener("scroll", sweep, { passive: true });

        window.removeEventListener("resize", sweep);

      }

    });

  };

  window.addEventListener("scroll", sweep, { passive: true });

  window.addEventListener("resize", sweep);

  setTimeout(sweep, 400);

}



