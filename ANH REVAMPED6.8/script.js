/* ---- Sport Predictor reference data ----

   STRIDE_M: average metres covered per step (walking/running/hiking only —

   cycling and swimming don't have a meaningful "step").

   SPEED_KMH: typical average speed used to estimate duration from distance.

   MET: Metabolic Equivalent of Task, used in the standard calorie formula:

   kcal = MET × weight(kg) × duration(hours). */

const STRIDE_M = { walking: 0.762, running: 1.0, hiking: 0.75 };

const SPEED_KMH = { walking: 5, running: 9, hiking: 4, cycling: 18, swimming: 3 };

const MET = { walking: 3.8, running: 9.8, hiking: 6, cycling: 7.5, swimming: 6 };



function predictActivityCalories({ activity, steps, distanceKm, weightKg }) {

    const safeWeight = weightKg > 0 ? weightKg : 70;

    let distance = distanceKm > 0 ? distanceKm : null;

    let stepsUsed = steps > 0 ? steps : null;



    if (!distance && stepsUsed) {

        const stride = STRIDE_M[activity];

        if (stride) distance = (stepsUsed * stride) / 1000;

    }

    if (!distance) return null;



    if (!stepsUsed) {

        const stride = STRIDE_M[activity];

        if (stride) stepsUsed = Math.round((distance * 1000) / stride);

    }



    const speed = SPEED_KMH[activity] || 5;

    const durationHours = distance / speed;

    const durationMin = durationHours * 60;

    const met = MET[activity] || 4;

    const calories = met * safeWeight * durationHours;



    return {

        activity,

        distanceKm: distance,

        steps: stepsUsed,

        durationMin,

        calories,

        weightKg: safeWeight

    };

}



