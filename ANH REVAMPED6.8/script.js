/* =========================================================

   AUTHENTICATION SYSTEM



   Storage: this file is meant to be run as a normal static

   site (e.g. via Live Server, or any real web host), not

   inside Claude.ai's artifact sandbox — so it uses the

   browser's real localStorage, wrapped in a tiny helper

   that mimics the { value } shape used throughout this file.

   If localStorage is unavailable (e.g. private browsing in

   some browsers), it falls back to an in-memory store for

   the current page load so the UI doesn't hard-crash.



   Google sign-in note: a real Google OAuth flow (Google

   Identity Services) needs a Google Cloud OAuth Client ID

   that only the site owner can generate — Claude can't

   provision one for you. Instead, "Continue with Google"

   here calls Puter's built-in account sign-in (puter.auth),

   which is already loaded on this page and supports signing

   in with Google as one of its providers, so the button is

   fully functional out of the box. If you get a real Google

   Client ID later, swap signInWithPuter() below for the

   Google Identity Services flow.

========================================================= */

const localStore = (() => {

  const memoryFallback = {};

  let hasLocalStorage = true;

  try {

    const testKey = "__anc_test__";

    window.localStorage.setItem(testKey, "1");

    window.localStorage.removeItem(testKey);

  } catch (error) {

    hasLocalStorage = false;

    console.warn("localStorage unavailable, using in-memory storage for this session only.", error);

  }



  return {

    async get(key) {

      const value = hasLocalStorage ? window.localStorage.getItem(key) : (memoryFallback[key] ?? null);

      if (value === null || value === undefined) {

        throw new Error(`No value for key: ${key}`);

      }

      return { key, value };

    },

    async set(key, value) {

      if (hasLocalStorage) {

        window.localStorage.setItem(key, value);

      } else {

        memoryFallback[key] = value;

      }

      return { key, value };

    }

  };

})();



