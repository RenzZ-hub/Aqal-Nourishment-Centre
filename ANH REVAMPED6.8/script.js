/* =========================================================

   PRELOADER — waits for all images, holds for a minimum time

   so the splash is perceivable, then fades out and unlocks

   scrolling. Hard-capped so the site never hangs on slow loads.

========================================================= */

(function setupPreloader() {

  var preloader = document.getElementById("preloader");

  if (!preloader) {

    document.documentElement.classList.add("page-ready");

    return;

  }

  var started = Date.now();

  // Mobile holds the splash longer so the entrance animations start

  // after fonts/layout have settled, avoiding first-paint stutter.

  var MIN_HOLD = (window.matchMedia && matchMedia("(max-width:600px)").matches) ? 1600 : 550;

  var MAX_WAIT = 4000;

  var hidden = false;



  document.body.style.overflow = "hidden";



  function hide() {

    if (hidden) return;

    hidden = true;

    preloader.classList.add("done");

    document.body.style.overflow = "";

    requestAnimationFrame(function () {

      document.documentElement.classList.add("page-ready");

      syncLenis();

    });

  }



  function doneLoading() {

    var wait = Math.max(0, MIN_HOLD - (Date.now() - started));

    setTimeout(hide, wait);

  }



  if (document.images.length === 0) { doneLoading(); return; }



  var total = document.images.length;

  var counted = 0;

  var finished = false;



  function check() {

    if (finished) return;

    var ready = true;

    for (var i = 0; i < document.images.length; i++) {

      if (!document.images[i].complete) { ready = false; break; }

    }

    if (ready || counted >= total) { finished = true; doneLoading(); }

  }



  for (var j = 0; j < document.images.length; j++) {

    (function (img) {

      if (img.complete) { counted++; check(); return; }

      img.addEventListener("load", function () { counted++; check(); });

      img.addEventListener("error", function () { counted++; check(); });

    })(document.images[j]);

  }

  check();

  setTimeout(hide, MAX_WAIT);

})();



/* =========================================================

   LENIS SMOOTH SCROLL (desktop only) — inertial, eased wheel

   scrolling. Disabled for mobile widths, coarse pointers,

   and Reduced Motion. Loads async from CDN; safe to miss.

========================================================= */

function startLenisRaf() {

  if (!window.__ancLenis || window.__ancLenisRafOn) return;

  window.__ancLenisRafOn = true;

  (function raf(time) {

    if (!window.__ancLenisRafOn) return;

    window.__ancLenis.raf(time);

    requestAnimationFrame(raf);

  })(performance.now());

}

function stopLenisRaf() { window.__ancLenisRafOn = false; }

function syncLenis() {

  const reduced = document.documentElement.classList.contains("motion-reduced");

  const fit = window.matchMedia("(min-width:601px) and (pointer:fine)").matches;

  if (reduced || !fit) {

    stopLenisRaf();

    if (window.__ancLenis) {

      try { window.__ancLenis.destroy(); } catch (e) {}

      window.__ancLenis = null;

    }

    return;

  }

  if (!window.__ancLenis) {

    initLenisSmoothScroll();

    return;

  }

  window.__ancLenis.start();

  startLenisRaf();

}

function initLenisSmoothScroll() {

  if (window.__ancLenis || document.documentElement.classList.contains("motion-reduced")) return;

  const mq = window.matchMedia("(min-width:601px) and (pointer:fine)");

  if (!mq.matches) return;

  const tag = document.createElement("script");

  tag.src = "https://cdn.jsdelivr.net/gh/studio-freight/lenis@1.0.23/bundled/lenis.min.js";

  tag.async = true;

  tag.onload = function () {

    if (typeof Lenis === "undefined") return;

    const saved = parseFloat(localStorage.getItem("anc_motion_speed"));

    let lerp = 0.1;

    if (saved === 1.7) lerp = 0.06;       // Slow: longest glide

    else if (saved === 0.4) lerp = 0.16;  // Fast: quickest response

    const lenis = new Lenis({

      lerp: lerp,

      wheelMultiplier: 0.7,

      gestureOrientation: "vertical",

      normalizeWheel: false,

      smoothTouch: false

    });

    [

      ".health-card", ".chat-messages", ".glass-select__menu",

      ".side-menu-content", ".forum-posts", ".scanner-card"

    ].forEach(function (sel) {

      const el = document.querySelector(sel);

      if (el) el.setAttribute("data-lenis-prevent", "");

    });

    window.__ancLenis = lenis;

    mq.addEventListener("change", syncLenis);

    syncLenis();

    document.addEventListener("click", function (ev) {

      if (!window.__ancLenisRafOn) return;

      const t = ev.target && ev.target.closest ? ev.target.closest('a[href^="#"]') : null;

      if (!t) return;

      const id = t.getAttribute("href");

      if (!id || id === "#") return;

      const el = document.querySelector(id);

      if (!el) return;

      ev.preventDefault();

      window.__ancLenis.scrollTo(el, { offset: -90 });

    });

  };

  document.head.appendChild(tag);

}



