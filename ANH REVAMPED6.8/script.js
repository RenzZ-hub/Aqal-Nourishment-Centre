function initSportProfileIntegration() {

  const sportWeight = document.getElementById("sportWeight");

  const sportModal = document.getElementById("sportModal");

  const weightField = sportWeight ? sportWeight.closest(".sport-field") : null;



  if (!sportWeight || !sportModal) return;



  function getProfileWeight() {

    try {

      const stored = window.localStorage.getItem("anc_account");

      if (!stored) return null;

      const account = JSON.parse(stored);

      const weight = parseFloat(account?.profile?.weight);

      return weight > 0 ? weight : null;

    } catch {

      return null;

    }

  }



  async function loadProfileWeight() {

    const weight = getProfileWeight();

    if (!weight) return;

    if (sportWeight.value) return;

    sportWeight.value = weight;

    showProfileBadge(weight);

  }



  function showProfileBadge(weight) {

    if (!weightField) return;

    const existing = weightField.querySelector(".profile-weight-badge");

    if (existing) return;



    const badge = document.createElement("div");

    badge.className = "profile-weight-badge";

    badge.innerHTML = `<i class="fa-solid fa-user-check"></i> Using your profile weight (${weight} kg)`;

    weightField.appendChild(badge);

  }



  sportModal.addEventListener("click", (event) => {

    if (event.target === sportModal) return;

    if (sportModal.classList.contains("active")) {

      loadProfileWeight();

    }

  });



  const observer = new MutationObserver((mutations) => {

    mutations.forEach((mutation) => {

      if (mutation.attributeName === "class" && sportModal.classList.contains("active")) {

        loadProfileWeight();

      }

    });

  });

  observer.observe(sportModal, { attributes: true });

}



