function ancWeightCalcTargets(profile, goal, variant) {

    var w = ancWeightGetNum(profile.weight, 65),
        h = ancWeightGetNum(profile.height, 170),
        age = ancWeightGetNum(profile.age, 24);

    var isMale = String(profile.gender).toLowerCase() === "male",
        isFemale = String(profile.gender).toLowerCase() === "female";

    var s = isMale ? 5 : isFemale ? -161 : 0;

    var bmr = 10 * w + 6.25 * h - 5 * age + s;

    if (bmr < 900) bmr = 1500;

    var tdee = Math.round(bmr * 1.35);

    var base = goal === "gain" ? tdee + 350 : tdee - 450;

    var vars = [-80, 0, 90, 40, -40];

    var adj = vars[variant % vars.length] || 0;

    var kcal = Math.max(1200, base + adj);

    var protein, carbs, fat;

    if (goal === "gain") {

        if (variant % 3 === 0) {
            protein = Math.round(w * 1.8);
            fat = Math.round(kcal * 0.28 / 9);
            carbs = Math.round((kcal - protein * 4 - fat * 9) / 4);
        } else if (variant % 3 === 1) {
            protein = Math.round(w * 1.6);
            fat = Math.round(kcal * 0.25 / 9);
            carbs = Math.round((kcal - protein * 4 - fat * 9) / 4);
        } else {
            protein = Math.round(w * 2.0);
            fat = Math.round(kcal * 0.30 / 9);
            carbs = Math.round((kcal - protein * 4 - fat * 9) / 4);
        }

    } else {

        if (variant % 3 === 0) {
            protein = Math.round(w * 1.8);
            fat = Math.round(kcal * 0.25 / 9);
            carbs = Math.round((kcal - protein * 4 - fat * 9) / 4);
        } else if (variant % 3 === 1) {
            protein = Math.round(w * 1.5);
            fat = Math.round(kcal * 0.22 / 9);
            carbs = Math.round((kcal - protein * 4 - fat * 9) / 4);
        } else {
            protein = Math.round(w * 2.0);
            fat = Math.round(kcal * 0.28 / 9);
            carbs = Math.round((kcal - protein * 4 - fat * 9) / 4);
        }

    }

    var focus = ["Balanced", "High Protein", "Energy Boost"][variant % 3];

    return { kcal: kcal, protein: Math.max(40, protein), carbs: Math.max(80, carbs), fat: Math.max(30, fat), focus: focus, variant: variant, baseTdee: tdee };

}

