/* Defeat leet/obfuscation tricks ("4njing", "ngentoooot", "a.n.j.i.n.g"):

   leet → letters, runs of 3+ → single char. Returns normalized text;

   pair with a spaceless copy to catch dotted/underscored evasions. */

var FORUM_LEET = { "4": "a", "@": "a", "3": "e", "1": "i", "0": "o", "5": "s", "$": "s", "7": "t", "+": "t", "8": "b", "9": "g", "6": "b" };

function forumNormalize(t) {

  let s = String(t || "").toLowerCase().replace(/[4@3105$7+8696]/g, function (c) { return FORUM_LEET[c] || c; });

  s = s.replace(/(.)\1{2,}/g, "$1");

  return s;

}

function forumModerate(text) {

  const t = String(text || "");

  if (!t.trim()) return { ok: true };

  const n = forumNormalize(t); // leet-proof copy

  const s = n.replace(/[^a-z]/g, ""); // spaceless copy (a.n.j.i.n.g → anjing)

  const hasAnywhere = (w) => forumHasWord(n, w) || forumHasWord(s, w);

  let i;

  for (i = 0; i < FORUM_DANGER.length; i++) {

    if (hasAnywhere(FORUM_DANGER[i])) return { ok: false, kind: "danger" };

  }

  for (i = 0; i < FORUM_HARD_WORDS.length; i++) {

    if (hasAnywhere(FORUM_HARD_WORDS[i])) return { ok: false, kind: "hard" };

  }

  let exempt = false;

  for (i = 0; i < FORUM_ANIMAL_EXEMPT.length; i++) {

    if (forumHasWord(n, FORUM_ANIMAL_EXEMPT[i])) { exempt = true; break; }

  }

  if (!exempt) {

    for (i = 0; i < FORUM_HARD_ANIMALS.length; i++) {

      if (hasAnywhere(FORUM_HARD_ANIMALS[i])) return { ok: false, kind: "hard" };

    }

  }

  // Mockery: insult within ~30 chars of a person-target (either order),

  // plus standalone rude phrases. Conditional advice is exempt.

  const T = "(kamu|kau|kalian|\\blu\\b|\\blo\\b|elo|anda|dia|mereka|dasar|you|\\bu\\b|yall)";

  const I = "(bodoh|goblok|tolol|dungu|idiot|bego|bloon|jelek|cebol|pendek|item|ireng|pesek|bau|miskin|melarat|cupu|norak|kampungan|lemah|pecundang|gagal|sampah|anjing|babi|monyet|stupid|dumb|ugly|loser|smelly)";

  const conditional = /\b(if|kalau|jika|bila|when|apabila)\b[\s\S]{0,50}\b(kamu|kau|kalian|lu|lo|elo|dia|mereka|you|u)\b/i.test(n);

  if (!conditional) {

    try {

      const re1 = new RegExp("\\b" + T + "\\b[\\s\\S]{0,30}\\b" + I + "\\b", "i");

      const re2 = new RegExp("\\b" + I + "\\b[\\s\\S]{0,30}\\b" + T + "\\b", "i");

      if (re1.test(n) || re2.test(n)) return { ok: false, kind: "mockery" };

    } catch (e) {}

  }

  for (i = 0; i < FORUM_MOCK_PHRASES.length; i++) {

    if (forumHasWord(n, FORUM_MOCK_PHRASES[i])) return { ok: false, kind: "mockery" };

  }

  for (i = 0; i < FORUM_GOSSIP.length; i++) {

    if (forumHasWord(n, FORUM_GOSSIP[i])) return { ok: false, kind: "gossip" };

  }

  return { ok: true };

}

