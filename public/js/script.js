const localStore = (() => {

  const memoryFallback = {};

  let hasLocalStorage = true;

  try {

    const testKey = "__anc_test__";

    window.localStorage.setItem(testKey, "1");

    window.localStorage.removeItem(testKey);

  } catch (error) {

    hasLocalStorage = false;

    console.warn("localStorage unavailable, using in-memory storage for this session only.", error);

  }



  return {

    async get(key) {

      const value = hasLocalStorage ? window.localStorage.getItem(key) : (memoryFallback[key] ?? null);

      if (value === null || value === undefined) {

        throw new Error(`No value for key: ${key}`);

      }

      return { key, value };

    },

    async set(key, value) {

      if (hasLocalStorage) {

        window.localStorage.setItem(key, value);

      } else {

        memoryFallback[key] = value;

      }

      return { key, value };

    }

  };

})();



