  /* Tombstone = "this id was deleted". Other devices purge their local

     copy when they see it — deletes propagate everywhere, even to

     devices that were offline at deletion time. */

  function forumCloudTombstone(id, kind) {

    if (!forumCloud.on || !id) return;

    try {

      forumCloud.db.collection("anc_deleted").doc(id).set(

        { kind: kind || "reply", time: Date.now() }, { merge: true }

      ).catch(function () {});

    } catch (e) {}

  }

  function forumCloudDeletePost(pid) {

    if (!forumCloud.on || !pid) return;

    try {

      forumCloud.db.collection("anc_posts").doc(pid).delete().catch(function () {});

      forumCloud.db.collection("anc_replies").where("post", "==", pid).get()

        .then(function (snap) { snap.forEach(function (d) { d.ref.delete().catch(function () {}); }); })

        .catch(function () {});

      forumCloudTombstone(pid, "post");

    } catch (e) {}

  }

  function forumPurgeLocal(id) {

    // Remove one id (post or reply) from the local store + page. Returns true if anything changed.

    let changed = false;

    try {

      const s = forumStoreLoad();

      const pb = s.userPosts.length;

      s.userPosts = s.userPosts.filter(function (p) { return p.id !== id; });

      if (s.userPosts.length !== pb) changed = true;

      if (s.replies[id]) { delete s.replies[id]; changed = true; }

      Object.keys(s.replies).forEach(function (pid) {

        const before = s.replies[pid].length;

        s.replies[pid] = s.replies[pid].filter(function (r) { return r.id !== id; });

        if (s.replies[pid].length !== before) changed = true;

      });

      if (changed) forumStoreWrite(s);

      const el = document.querySelector('[data-forum-id="' + id + '"]');

      if (el) { el.remove(); changed = true; }

    } catch (e) {}

    return changed;

  }

