/* =========================================================

   GLASS DROPDOWNS — custom layered listboxes over native selects

========================================================= */

function enhanceSelect(select) {

  if (!select || select.dataset.glass) return;



  const root = document.createElement("span");

  root.className = "glass-menu-root";

  select.classList.add("glass-native");

  select.dataset.glass = "1";

  select.parentNode.insertBefore(root, select);

  root.appendChild(select);



  const valueEl = document.createElement("span");

  valueEl.className = "glass-select__value";



  const chevron = document.createElement("span");

  chevron.className = "glass-select__chevron";

  chevron.setAttribute("aria-hidden", "true");

  chevron.innerHTML = '<i class="fa-solid fa-chevron-down"></i>';



  const button = document.createElement("button");

  button.type = "button";

  button.className = "glass-select";

  button.setAttribute("role", "combobox");

  button.setAttribute("aria-expanded", "false");

  button.setAttribute("aria-haspopup", "listbox");

  button.appendChild(valueEl);

  button.appendChild(chevron);



  const menuId = "glassMenu-" + (select.id || Math.random().toString(36).slice(2, 7));

  const menu = document.createElement("div");

  menu.className = "glass-select__menu";

  menu.id = menuId;

  menu.setAttribute("role", "listbox");

  button.setAttribute("aria-controls", menuId);



  const items = [];

  Array.from(select.options).forEach((opt, idx) => {

    const row = document.createElement("button");

    row.type = "button";

    row.className = "glass-select__item";

    row.setAttribute("role", "option");

    row.setAttribute("aria-selected", opt.selected ? "true" : "false");

    row.textContent = opt.textContent;

    if (opt.disabled) row.disabled = true;

    const check = document.createElement("span");

    check.className = "glass-select__check";

    check.innerHTML = '<i class="fa-solid fa-check"></i>';

    row.appendChild(check);

    row.addEventListener("click", () => pick(idx));

    menu.appendChild(row);

    items.push(row);

  });



  root.appendChild(button);

  root.appendChild(menu);



  let open = false;



  const selectedIndex = () => select.selectedIndex;

  const sync = () => {

    const opt = select.options[selectedIndex()];

    valueEl.textContent = opt ? opt.textContent : "";

    items.forEach((row, i) => {

      row.setAttribute("aria-selected", i === selectedIndex() ? "true" : "false");

    });

  };



  const setOpen = (v, focusIdx) => {

    open = v;

    root.classList.toggle("is-open", v);

    button.setAttribute("aria-expanded", v ? "true" : "false");

    const wrap = root.closest(".sport-select-wrap");

    if (wrap) wrap.classList.toggle("is-open", v);

    if (v) {

      const idx = focusIdx >= 0 ? focusIdx : selectedIndex() >= 0 ? selectedIndex() : 0;

      const rect = root.getBoundingClientRect();

      menu.style.visibility = "hidden";

      const mh = menu.getBoundingClientRect().height;

      menu.style.visibility = "";

      const below = window.innerHeight - rect.bottom;

      root.classList.toggle("is-above", below < mh + 56);

      if (focusIdx >= 0 && items[idx]) items[idx].focus();

    } else {

      root.classList.remove("is-above");

    }

  };



  const pick = (i) => {

    if (items[i] && items[i].disabled) return;

    select.value = select.options[i].value;

    select.dispatchEvent(new Event("change", { bubbles: true }));

    sync();

    setOpen(false);

    button.focus();

  };



  button.addEventListener("click", (e) => {

    e.stopPropagation();

    setOpen(open ? false : true);

  });



  button.addEventListener("keydown", (e) => {

    if (e.key === "ArrowDown") {

      e.preventDefault();

      setOpen(true, selectedIndex() >= 0 ? selectedIndex() : 0);

    } else if (e.key === "ArrowUp") {

      e.preventDefault();

      setOpen(true, items.length - 1);

    } else if (e.key === "Enter" || e.key === " ") {

      e.preventDefault();

      if (!open) setOpen(true);

    } else if (e.key === "Escape") {

      setOpen(false);

    }

  });



  items.forEach((row, i) => {

    row.addEventListener("mouseenter", () => {

      items.forEach(r => r.classList.remove("is-key"));

      row.classList.add("is-key");

    });

    row.addEventListener("keydown", (e) => {

      if (e.key === "ArrowDown") {

        e.preventDefault();

        const next = (i + 1) % items.length;

        items[next].focus();

      } else if (e.key === "ArrowUp") {

        e.preventDefault();

        const prev = (i - 1 + items.length) % items.length;

        items[prev].focus();

      } else if (e.key === "Enter" || e.key === " ") {

        e.preventDefault();

        pick(i);

      } else if (e.key === "Escape") {

        setOpen(false);

        button.focus();

      } else if (e.key === "Tab") {

        setOpen(false);

      }

    });

  });



  document.addEventListener("pointerdown", (e) => {

    if (open && !root.contains(e.target)) setOpen(false);

  }, true);

  window.addEventListener("resize", () => { if (open) setOpen(false); });

  window.addEventListener("scroll", () => { if (open) setOpen(false); }, true);



  sync();

}



