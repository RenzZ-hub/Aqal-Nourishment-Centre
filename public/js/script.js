  async function runScanner() {

    if (!selectedImageFile) return;



    scannerResultBox.style.display = "block";

    scannerResultText.innerHTML = `<i class="fa-solid fa-spinner fa-spin"></i> ${ancT("scanner.analyzing")}`;

    macroChartWrap.style.display = "none";

    proteinWarningBox.style.display = "none";

    sugarWarningBox.style.display = "none";

    runScanBtn.disabled = true;



    // 0) Gemini smart scan first (server key, knows Indonesian food).

    try {

      if (await tryGeminiScan()) {

        runScanBtn.disabled = false;

        return;

      }

    } catch (e) { /* fall through to HF flow */ }



    let foodName = null;



    const hfToken = getHfToken();

    if (!hfToken) {

      scannerResultText.innerHTML = `

        <strong>${ancT("scanner.noToken")}</strong><br>

        <input type="password" id="inlineHfToken" class="hf-token-input inline" placeholder="hf_..." autocomplete="off" spellcheck="false" aria-label="Hugging Face API key">

        <button id="inlineHfSave" class="scanner-btn secondary inline-save">${ancT("settings.saveToken")}</button>

      `;

      const inlineInput = document.getElementById("inlineHfToken");

      const inlineSave = document.getElementById("inlineHfSave");

      if (inlineInput && inlineSave) {

        inlineSave.addEventListener("click", () => {

          setHfToken(inlineInput.value);

          if (getHfToken()) runScanner();

        });

        inlineInput.addEventListener("keydown", (e) => {

          if (e.key === "Enter") {

            setHfToken(inlineInput.value);

            if (getHfToken()) runScanner();

          }

        });

        setTimeout(() => inlineInput.focus(), 60);

      }

      showScannerManual();

      runScanBtn.disabled = false;

      return;

    }



    let results = null;

    try {

      const vision = await fetchVisionResult(selectedImageFile, hfToken);

      const response = { ok: vision.ok, status: vision.status };

      const reply = vision.reply;



      if (!response.ok) {

        const errCode = reply && reply.error;

        console.error("Vision service error:", response.status, errCode);

        let message = ancT("scanner.error");

        if (response.status === 403) {

          message = ancT("scanner.token403");

        } else if (response.status === 401) {

          message = ancT("scanner.tokenInvalid");

        } else if (response.status === 503 || (errCode && /loading/i.test(errCode))) {

          message = ancT("scanner.loading");

        }

        scannerResultText.innerHTML = `${escapeHTML(message)}<br><span style="opacity:.6">(HTTP ${response.status})</span><br><br>${ancT("scanner.manualHint")}`;

        showScannerManual();

        runScanBtn.disabled = false;

        return;

      }



      results = Array.isArray(reply) ? reply : null;

    } catch (error) {

      console.error("Scanner error:", error);

      scannerResultText.innerHTML = `<strong>${escapeHTML(ancT("scanner.error"))}</strong><br><br>${ancT("scanner.manualHint")}`;

      showScannerManual();

      runScanBtn.disabled = false;

      return;

    }



    if (Array.isArray(results) && results.length > 0) {

      const top = results[0];

      const confidence = top.score * 100;

      if (top.score < 0.3) {

        // Too unsure (e.g. sambal bottle read as "churros" at 9%) —

        // don't present the guess as fact, ask the user instead.

        foodName = null;

        scannerResultText.innerHTML = `

          <strong>${ancT("scanner.unsureTitle")}</strong><br>

          ${ancT("scanner.unsure", { v: escapeHTML(top.label.replace(/_/g, " ").toUpperCase()), c: confidence.toFixed(1) })}

        `;

        showScannerManual();

      } else {

        foodName = top.label.replace(/_/g, " ");



        scannerResultText.innerHTML = `

          <strong>${ancT("scanner.detected")}</strong> ${foodName.toUpperCase()}<br>

          <span style="color:#88deb0">${confidence.toFixed(1)}% ${ancT("scanner.confidence")}</span><br><br>

          ${ancT("scanner.estimating")}

        `;

      }

    } else {

      scannerResultText.innerHTML = `<strong>${escapeHTML(ancT("scanner.couldntIdentify"))}</strong><br><br>${ancT("scanner.manualHint")}`;

      showScannerManual();

    }



    if (foodName) {

      await estimateAndRenderMacros(foodName);

    }



    runScanBtn.disabled = false;

  }



