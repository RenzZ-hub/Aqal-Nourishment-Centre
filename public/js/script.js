  /* --- Global animation-speed multiplier ----------------------------

     Scales every element's real animation duration/delay and

     transition duration proportionally, preserving rhythm. Originals

     are cached so switching back to Normal always restores them. --- */

  const speedOriginals = new WeakMap();

  function captureSpeed(el) {

    if (speedOriginals.has(el)) return;

    const cs = getComputedStyle(el);

    speedOriginals.set(el, {

      ad: cs.animationDuration,

      ad2: cs.animationDelay,

      td: cs.transitionDuration

    });

  }

  function applySpeed(factor) {

    const all = document.querySelectorAll("*");

    for (const el of all) {

      captureSpeed(el);

      const o = speedOriginals.get(el);

      const a = csTimeToMs(o.ad), d = csTimeToMs(o.ad2), t = csTimeToMs(o.td);

      el.style.animationDuration = a ? (a * factor) + "ms" : "";

      el.style.animationDelay = d ? (d * factor) + "ms" : "";

      el.style.transitionDuration = t ? (t * factor) + "ms" : "";

    }

  }

  function csTimeToMs(val) {

    if (!val) return 0;

    const m = /^([\d.]+)(s|ms)$/.exec(val.trim());

    if (!m) return 0;

    return m[2] === "ms" ? parseFloat(m[1]) : parseFloat(m[1]) * 1000;

  }



