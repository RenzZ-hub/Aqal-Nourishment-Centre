async function ancAiChatServer(prompt) {
  const ctrl = new AbortController();
  const timer = setTimeout(function () { try { ctrl.abort(); } catch (e) {} }, 15000);
  try {
    const res = await fetch("/api/ai-chat", {
      method: "POST",
      signal: ctrl.signal,
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ prompt })
    });
    if (res.status === 501) throw ancAiError("NO_GEMINI");
    if (res.status === 429) {
      const d429 = await res.json().catch(() => null);
      if (d429 && d429.error === "GEMINI_BUSY") throw ancAiError("GEMINI_BUSY", d429);
      throw ancAiError("FAILED", d429);
    }
    const data = await res.json().catch(() => null);
    if (!res.ok || !data || typeof data.text !== "string" || !data.text.trim()) {
      throw ancAiError("FAILED", data);
    }
    return data.text.trim();
  } finally {
    clearTimeout(timer);
  }
}
