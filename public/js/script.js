  function animateHealthHeight(card, startHeight, endHeight, duration = 380) {

    if (!card || startHeight === endHeight) return;

    card.style.overflow = "hidden";

    const startTime = performance.now();



    function easeInOutCubic(t) {

      return t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2;

    }



    function step(now) {

      const progress = Math.min((now - startTime) / duration, 1);

      card.style.height = `${startHeight + (endHeight - startHeight) * easeInOutCubic(progress)}px`;

      if (progress < 1) requestAnimationFrame(step);

      else {

        card.style.height = "";

        card.style.overflow = "";

      }

    }



    requestAnimationFrame(step);

  }



