  /* Vision via same-origin proxy first (server holds HF_TOKEN, so it

     works for every visitor with zero config), then direct HF call

     with the user's token as fallback (e.g. plain static hosting). */

  async function fetchVisionResult(file, hfToken) {

    try {

      const pRes = await fetch("/api/scan", {

        method: "POST",

        headers: { "Content-Type": file.type },

        body: file

      });

      const pText = await pRes.text().catch(() => "");

      let pJson = null;

      try { pJson = JSON.parse(pText); } catch (e) {}

      if (pJson !== null && !(pRes.status === 502 && pJson.error === "SCAN_NOT_CONFIGURED")) {

        return { ok: pRes.ok, status: pRes.status, reply: pJson };

      }

      // Proxy has no token configured, or unparsable reply → direct call.

    } catch (e) {

      // Proxy unreachable → direct call.

    }

    const response = await fetch("https://router.huggingface.co/hf-inference/models/nateraw/food", {

      method: "POST",

      headers: {

        "Content-Type": file.type,

        "Authorization": `Bearer ${hfToken}`

      },

      body: file

    });

    const reply = await response.json().catch(() => null);

    return { ok: response.ok, status: response.status, reply };

  }



