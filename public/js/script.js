function renderMacroChart(elements, data) {

  const { macroChartWrap, macroDonut, macroLegend, macroCalories } = elements;



  const protein = Math.max(0, data.protein_g);

  const carbs = Math.max(0, data.carbs_g);

  const fat = Math.max(0, data.fat_g);



  const proteinCalories = protein * 4;

  const carbsCalories = carbs * 4;

  const fatCalories = fat * 9;



  const total = proteinCalories + carbsCalories + fatCalories;

  const calories = data.calories > 0 ? data.calories : total;

  const safeTotal = total || 1;



  const proteinPercentage = (proteinCalories / safeTotal) * 100;

  const carbsPercentage = (carbsCalories / safeTotal) * 100;

  const fatPercentage = (fatCalories / safeTotal) * 100;



  const proteinDegrees = (proteinPercentage / 100) * 360;

  const carbsDegrees = (carbsPercentage / 100) * 360;



  macroDonut.style.background = `conic-gradient(

    ${MACRO_COLORS.protein} 0deg ${proteinDegrees}deg,

    ${MACRO_COLORS.carbs} ${proteinDegrees}deg ${proteinDegrees + carbsDegrees}deg,

    ${MACRO_COLORS.fat} ${proteinDegrees + carbsDegrees}deg 360deg

  )`;



  macroCalories.innerText = Math.round(calories);



  macroLegend.innerHTML = `

    <li><span class="macro-dot" style="background:${MACRO_COLORS.protein}"></span>${ancT("macro.proteinLabel")}: ${protein}g (${proteinPercentage.toFixed(0)}%)</li>

    <li><span class="macro-dot" style="background:${MACRO_COLORS.carbs}"></span>${ancT("macro.carbsLabel")}: ${carbs}g (${carbsPercentage.toFixed(0)}%)</li>

    <li><span class="macro-dot" style="background:${MACRO_COLORS.fat}"></span>${ancT("macro.fatLabel")}: ${fat}g (${fatPercentage.toFixed(0)}%)</li>

  `;



  macroChartWrap.style.display = "flex";

}





